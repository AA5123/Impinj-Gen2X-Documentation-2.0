#!/usr/bin/env node
/**
 * ONE ICON LIBRARY: Lucide. This script is what makes that true rather than aspirational.
 *
 * WHAT IT OWNS
 *   1. assets/icons/lucide/*.svg   — the vendored source SVGs, copied verbatim from
 *                                    lucide-static so the ISC licence header travels with them.
 *   2. The `--sb-icon-*` custom properties in src/css/sidebar-icons.scss, between the two
 *      GENERATED markers. Everything outside those markers is hand-written and untouched.
 *
 * WHY TWO DELIVERY MECHANISMS FOR ONE LIBRARY, which looks like duplication and is not.
 * React surfaces (the landing page) import components from `lucide-react`. The sidebar rows
 * and DocCard tiles CANNOT: they are decorated by CSS `mask-image` on a pseudo-element, so
 * what they need is a data URI, not a JSX element. Same icons, same library, same version —
 * two consumers with genuinely different requirements. src/components/icons/index.tsx is the
 * React half and is hand-written; this script is the CSS half.
 *
 * WHY THE SVGs ARE VENDORED AT ALL, when lucide-static is right there in node_modules.
 * So that the tree carries its own icons: a reader of this repository can see exactly which
 * 34 glyphs the site uses without installing anything, and a diff shows when one changes.
 * lucide-static stays a pinned devDependency because it is where new icons come FROM.
 *
 * TWO LEGAL STATES, AND NOTHING BETWEEN THEM. The vendored folder is either
 *
 *   LIBRARY  — the complete lucide-static set (2,025 SVGs), so an author can browse and pick
 *              an icon from the working tree without a network round trip. Deliberate and
 *              TEMPORARY: the owner's instruction of 2026-08-16 is "add all assets now, remove
 *              the unused ones once the documentation is done."
 *   PRUNED   — exactly the icons the site uses, which is the end state.
 *
 * `--check` enforces "one or the other", so a half-vendored tree is still a hard failure and
 * dead weight cannot accumulate unnoticed the way it could if extras were simply tolerated.
 *
 * WHAT THE COST ACTUALLY IS, because the previous note here got it wrong by 18x and the wrong
 * number was the whole argument. It read: "7.9 MB committed today stays in every clone even
 * after it is deleted." 7.9 MB is the figure `du -sh` reports for the raw folder. Git does not
 * store it that way — 2,025 Lucide SVGs are near-identical 24x24 stroke paths, so they delta
 * against each other almost perfectly. Measured, not reasoned:
 *
 *   git init /tmp/t && cp -R node_modules/lucide-static/icons /tmp/t && git -C /tmp/t add -A
 *   git -C /tmp/t commit -m x && git -C /tmp/t gc --aggressive
 *   git -C /tmp/t count-objects -vH   ->  size-pack: 428.35 KiB
 *
 * 428 KiB, against this repository's 4.33 MiB pack: about 10%, not the doubling the raw figure
 * implies. The same note claimed "this repository has already paid for that lesson once";
 * `git log --diff-filter=D` finds zero deleted binary assets in the history, so that did not
 * happen here. Both statements are corrected rather than deleted so the next person can see
 * why the decision changed.
 *
 * The permanence point itself still stands — pruning later does not reclaim the 428 KiB — it
 * is simply a small enough number to be worth the convenience, which is the owner's call and
 * was made with the measurement in hand.
 *
 * USAGE
 *   node scripts/site/generate-icons.mjs            # regenerate tokens; vendor what is used
 *   node scripts/site/generate-icons.mjs --library  # vendor ALL 2,025 (the browsing state)
 *   node scripts/site/generate-icons.mjs --prune    # reduce to the used set (the end state)
 *   node scripts/site/generate-icons.mjs --check    # CI: exit 1 unless LIBRARY or PRUNED
 */
