const read = (name) => {
  const p = path.join(SRC, `${name}.svg`);
  if (!fs.existsSync(p)) {
    console.error(`FAIL — lucide-static has no icon "${name}" (looked in ${p}).`);
    console.error('       Check the name at https://lucide.dev/icons — v1 renamed many.');
    process.exit(1);
  }
  return fs.readFileSync(p, 'utf8');
};

/** Upstream SVG -> a data URI usable as a CSS mask-image. */
function toDataUri(svg) {
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, '')          // drop the licence comment (kept in the vendored file)
    .replace(/\s*\n\s*/g, ' ')                 // one line
    .replace(/\s{2,}/g, ' ')
    .replace(/\sclass="[^"]*"/g, '')           // the lucide-* class is meaningless inside a mask
    .replace(/\swidth="24"|\sheight="24"/g, '') // the mask element sets its own box
    .replace(/stroke-width="2"/, `stroke-width="${STROKE_WIDTH}"`)
    /* A LITERAL '#', not '%23'. The escape chain below turns '%' into '%25' first, so a
     * pre-encoded '%23' would come out as '%2523000' — a colour no parser accepts, and the
     * mask silently renders nothing. Let one place own the encoding. */
    .replace(/stroke="currentColor"/, 'stroke="#000"') // a mask needs opaque paint, any colour
    .trim();
  /* encodeURIComponent is too aggressive and too large for a data URI; only these five
   * characters actually have to be escaped inside a double-quoted url(). */
  const enc = body
    .replace(/%/g, '%25')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')
    .replace(/#/g, '%23')
    .replace(/"/g, "'")
    .replace(/\s/g, '%20');
  return `url("data:image/svg+xml,${enc}")`;
}

function build() {
  const lines = [BEGIN];
  for (const [token, icon] of Object.entries(REGISTRY)) {
    lines.push(`  --sb-icon-${token}: ${toDataUri(read(icon))};`);
  }
  lines.push(END);
  return lines.join('\n');
}

function splice(text, block) {
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a === -1 || b === -1) {
    console.error(`FAIL — ${SCSS} is missing the GENERATED markers. Restore them around the`);
    console.error('       --sb-icon-* declarations, or this script cannot find its region.');
    process.exit(1);
  }
  return text.slice(0, a) + block + text.slice(b + END.length);
}

const check = process.argv.includes('--check');
const library = process.argv.includes('--library');
const prune = process.argv.includes('--prune');
if (library && prune) {
  console.error('FAIL — --library and --prune are opposites; pass one.');
  process.exit(1);
}

const current = fs.readFileSync(SCSS, 'utf8');
const next = splice(current, build());

/* Vendor every icon either half uses. */
const wanted = [...new Set([...Object.values(REGISTRY), ...REACT_ICONS])].sort();
/* The complete upstream set — the other legal state of the vendored folder. */
const everything = fs.readdirSync(SRC).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort();

fs.mkdirSync(VENDOR, { recursive: true });
const onDisk = fs.readdirSync(VENDOR).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort();
const missing = wanted.filter((n) => !onDisk.includes(n));
const extra = onDisk.filter((n) => !wanted.includes(n));
const sameSet = (a, b) => a.length === b.length && a.every((x, i) => x === b[i]);
const isPruned = sameSet(onDisk, wanted);
const isLibrary = sameSet(onDisk, everything);

if (check) {
  const problems = [];
  if (next !== current) problems.push(`${SCSS} is stale`);
  if (missing.length) problems.push(`${missing.length} icon(s) not vendored: ${missing.join(', ')}`);
  /* THE INVARIANT: the folder is one of the two legal states. Tolerating "anything with the
   * used icons present" would let dead weight accumulate silently, which is the failure the
   * strict extras-check used to prevent; requiring an exact set keeps that protection in both
   * states instead of trading it away. */
  if (!isPruned && !isLibrary) {
    problems.push(
      `${onDisk.length} SVG(s) vendored — neither the used set (${wanted.length}) ` +
      `nor the complete library (${everything.length}). ${extra.length} unexpected: ` +
      `${extra.slice(0, 8).join(', ')}${extra.length > 8 ? `, +${extra.length - 8} more` : ''}`
    );
  }
  if (problems.length) {
    console.error('FAIL — icon tree is out of date:');
    for (const p of problems) console.error(`  ${p}`);
    console.error('\nRun one of:');
    console.error('  node scripts/site/generate-icons.mjs --library   # browse-everything state');
    console.error('  node scripts/site/generate-icons.mjs --prune     # ship-only-what-is-used');
    process.exit(1);
  }
  console.log(
    `generate-icons --check — OK (${onDisk.length} SVGs vendored, ` +
    `state=${isLibrary ? 'LIBRARY' : 'PRUNED'}, ${Object.keys(REGISTRY).length} mask tokens current)` +
    (isLibrary ? `\n  NOTE: LIBRARY state — ${extra.length} of ${onDisk.length} are unused.` +
                 ' Run `npm run icons:prune` when the documentation is done.' : '')
  );
  process.exit(0);
}

const target = library ? everything : prune ? wanted : [...new Set([...wanted, ...onDisk])].sort();
for (const n of target) fs.writeFileSync(path.join(VENDOR, `${n}.svg`), read(n));
const removed = onDisk.filter((n) => !target.includes(n));
for (const n of removed) fs.rmSync(path.join(VENDOR, `${n}.svg`));
fs.writeFileSync(SCSS, next);
console.log(`generate-icons — ${target.length} SVG(s) in ${VENDOR}/` +
  (removed.length ? `, removed ${removed.length}` : '') +
  `; regenerated ${Object.keys(REGISTRY).length} mask tokens in ${SCSS}` +
  (library ? `\n  LIBRARY state: ${target.length - wanted.length} unused icons vendored for browsing.` : ''));
