def selftest() -> int:
    bad = 0
    for path, want in FIXTURES:
        got = check(path)
        got_rule = got[0] if got else None
        if got_rule != want:
            bad += 1
            print('FIXTURE FAIL  %-58s want %-14s got %s' % (path, want, got_rule))
    if bad:
        print('self-test: %d of %d fixtures FAILED' % (bad, len(FIXTURES)))
        return 1
    n_fail = sum(1 for _, w in FIXTURES if w)
    print('self-test: %d fixtures, all pass (%d of them must produce a finding)'
          % (len(FIXTURES), n_fail))
    return 0


