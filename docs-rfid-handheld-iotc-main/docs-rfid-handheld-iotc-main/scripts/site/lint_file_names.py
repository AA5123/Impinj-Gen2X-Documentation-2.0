# Names the ecosystem or a framework fixes.  A rule that fights these loses.
RESERVED_STEMS = {
    'index', 'page', 'layout', 'default', 'main', 'not-found', '_category_',
}
RESERVED_BASENAMES = {
    'README.md', 'LICENSE', 'LICENSE.md', 'LICENCE', 'NOTICE', 'CHANGELOG.md',
    'CONTRIBUTING.md', 'CODE_OF_CONDUCT.md', 'SECURITY.md', 'SUPPORT.md', 'GOVERNANCE.md',
    'ADOPTERS.md', 'DEI.md', 'AUTHORS', 'INSTALL', 'MANIFEST', 'CODEOWNERS', 'Makefile',
    'Dockerfile', 'package.json', 'package-lock.json', 'tsconfig.json', 'requirements.txt',
    'docusaurus.config.ts', 'babel.config.js', 'jest.config.js',
}

# Layer 3 carve-out: a NORMATIVE GOVERNANCE DOCUMENT may be SCREAMING_SNAKE_CASE .md.
# Precedent is not invented here -- GitHub's own community-health filenames are uppercase and
# `CODE_OF_CONDUCT.md` carries underscores, so the form already means "this file binds the
# repository" to every developer who has used the forge.
GOVERNANCE_DOC = re.compile(r'^[A-Z][A-Z0-9]*(_[A-Z0-9]+)*\.md$')

# Compound suffixes that are part of the TYPE, not of the name.  Stripped before the stem is
# graded, or `iotc-rfd40-90-mqtt.asyncapi.json` grades as "other" and the contract -- which can
# never be renamed -- becomes a permanent finding.
COMPOUND_SUFFIXES = (
    '.module.css', '.module.scss', '.d.ts', '.config.ts', '.config.js', '.config.mjs',
    '.template.html', '.asyncapi.json', '.openapi.json', '.test.ts', '.test.tsx',
    '.spec.ts', '.spec.tsx', '.stories.tsx',
)

KEBAB = re.compile(r'^[a-z0-9]+(-[a-z0-9]+)*$')
FLAT = re.compile(r'^[a-z0-9]+$')
SNAKE = re.compile(r'^[a-z_][a-z0-9_]*$')
PASCAL = re.compile(r'^[A-Z][A-Za-z0-9]*$')
CAMEL = re.compile(r'^[a-z][A-Za-z0-9]*$')
POSIX_SET = re.compile(r'^[A-Za-z0-9._-]+$')


def split_name(basename: str) -> tuple[str, str]:
    """-> (stem, suffix). Compound suffixes are honoured; otherwise the LAST dot wins."""
    for suf in COMPOUND_SUFFIXES:
        if basename.endswith(suf) and len(basename) > len(suf):
            return basename[: -len(suf)], suf
    if '.' in basename[1:]:
        i = basename.rindex('.')
        return basename[:i], basename[i:]
    return basename, ''


def layer_for(suffix: str) -> str:
    if suffix == '.py':
        return 'L1'
    if suffix in ('.json', '.yml', '.yaml', '.toml', '.asyncapi.json', '.openapi.json'):
        return 'L2'
    if suffix in ('.md', '.mdx'):
        return 'L3'
    if suffix in ('.tsx', '.jsx'):
        return 'L4'
    if suffix in ('.ts', '.mjs', '.js', '.cjs', '.d.ts', '.config.ts', '.config.js',
                  '.config.mjs', '.test.ts', '.test.tsx', '.spec.ts', '.spec.tsx',
                  '.stories.tsx'):
        return 'L4b'
    if suffix in ('.css', '.scss', '.module.css', '.module.scss'):
        return 'L4c'
    if suffix == '.sh':
        return 'L5'
    return 'L6'


def check(path: str) -> tuple[str, str] | None:
    """-> (rule, message) on a finding, else None."""
    basename = path.rsplit('/', 1)[-1]

    if basename in RESERVED_BASENAMES or basename.startswith('.'):
        return None

    # --- Layer 0: the system floor.  Applies to every in-scope file, no exceptions. -------------
    if basename.startswith('-'):
        return ('L0-hyphen', 'leading hyphen: a shell or CLI reads this as an option, not a file')
    if not POSIX_SET.match(basename):
        offending = sorted({c for c in basename if not POSIX_SET.match(c)})
        return ('L0-posix',
                'outside the POSIX Portable Filename Character Set (IEEE Std 1003.1) '
                '-- offending: %s' % ' '.join(repr(c) for c in offending))

    stem, suffix = split_name(basename)
    if stem in RESERVED_STEMS:
        return None
    layer = layer_for(suffix)

    if layer == 'L1':
        if not SNAKE.match(stem):
            return ('L1-python',
                    'Python MUST be snake_case or flat (PEP 8); a hyphen makes the stem '
                    'un-importable, so the name cannot survive the file becoming a module')
    elif layer == 'L2':
        if not KEBAB.match(stem):
            return ('L2-config', 'configuration and data artifacts MUST be kebab-case')
    elif layer == 'L3':
        if not (KEBAB.match(stem) or GOVERNANCE_DOC.match(basename)):
            return ('L3-doc',
                    'documentation stems become URL path segments (RFC 3986 section 2.3) and MUST be '
                    'lowercase kebab-case; the only exception is a SCREAMING_SNAKE_CASE '
                    'normative governance document')
    elif layer == 'L4':
        if not (PASCAL.match(stem) or KEBAB.match(stem)):
            return ('L4-component',
                    'a component file MUST be PascalCase matching its exported identifier; '
                    'a route file MUST be kebab-case')
    elif layer == 'L4b':
        if not (KEBAB.match(stem) or CAMEL.match(stem) or PASCAL.match(stem)):
            return ('L4b-module',
                    'a TS/JS module MUST be kebab-case, camelCase or PascalCase '
                    '-- never snake_case, which is not a convention in this ecosystem')
    elif layer == 'L4c':
        if not (KEBAB.match(stem) or PASCAL.match(stem)):
            return ('L4c-style',
                    'a stylesheet MUST be kebab-case, or PascalCase when it is a CSS Module '
                    'co-located with the component of that name')
    elif layer == 'L5':
        if not KEBAB.match(stem):
            return ('L5-script', 'a shell script MUST be kebab-case')
    else:
        if not (KEBAB.match(stem) or FLAT.match(stem)):
            return ('L6-asset', 'assets and everything else MUST be kebab-case')
    return None


def _git_z(args: list[str]) -> list[str]:
    """Run a git command whose output is NUL-delimited and split it correctly.

    NUL-delimited is not a stylistic choice. 86 tracked basenames in this repository contain a
    space, a comma, a bracket or an emoji; a newline- or space-split listing mis-parses every one
    of them, and git quotes such paths by default, which a naive splitter then reads as literal
    backslashes.
    """
    out = subprocess.run(['git', *args], capture_output=True, check=True).stdout
    return [f for f in out.decode('utf-8', 'surrogateescape').split('\0') if f]


def tracked() -> list[str]:
    return _git_z(['ls-files', '-z'])


def staged() -> list[str]:
    """Only files this commit ADDS or RENAMES.

    A naming violation cannot be introduced any other way, so this is the scope that lets the
    pre-commit hook be installed with no preconditions: it stops new violations immediately
    without sitting red on the names the migration ledger has yet to clear.
    """
    return _git_z(['diff', '--cached', '-z', '--name-only', '--diff-filter=AR'])


def exempt_reason(path: str) -> str | None:
    for prefix, why in EXEMPT_TREES:
        if path.startswith(prefix):
            return why
    return None


def main(argv: list[str]) -> int:
    if '--selftest' in argv:
        return selftest()
    if selftest():
        print('ABORT: the checker fails its own fixtures')
        return 1

    is_staged = '--staged' in argv
    files = staged() if is_staged else tracked()
    scoped = [f for f in files if exempt_reason(f) is None]
    findings = []
    for f in scoped:
        r = check(f)
        if r:
            findings.append((r[0], f, r[1]))

    if '--census' in argv:
        print('tracked %d | in scope %d | exempt %d'
              % (len(files), len(scoped), len(files) - len(scoped)))
        for prefix, why in EXEMPT_TREES:
            n = sum(1 for f in files if f.startswith(prefix))
            if n:
                print('  %-24s %5d  %s' % (prefix, n, why[:64]))
        print('findings: %d' % len(findings))
        return 0

    for rule, path, msg in sorted(findings):
        print('%-14s %s\n               %s' % (rule, path, msg))
    if is_staged:
        if findings:
            print()
            print('commit blocked: %d staged filename(s) do not conform.' % len(findings))
            print('See docs/standards/FILE_NAMING_SPECIFICATION.md section 4.')
        return 1 if findings else 0
    print()
    print('%d tracked, %d in scope, %d findings' % (len(files), len(scoped), len(findings)))
    return 1 if findings else 0


# --- fixtures ------------------------------------------------------------------------------------
