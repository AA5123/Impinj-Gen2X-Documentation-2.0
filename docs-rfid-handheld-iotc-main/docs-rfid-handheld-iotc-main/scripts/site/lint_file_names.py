#!/usr/bin/env python3
"""Enforce docs/standards/FILE_NAMING_SPECIFICATION.md against the git index.

Reads `git ls-files -z` -- NULL-delimited, deliberately. A newline- or space-split listing
mis-parses the 86 tracked basenames in this repository that contain a space, a comma, a bracket
or an emoji, and a censusing bug of exactly that kind has already produced one false claim in
this project's history.

    python3 scripts/site/lint_file_names.py             report every finding, exit 1 if any
    python3 lint_file_names.py --selftest  run the rule fixtures, exit 1 on failure
    python3 lint_file_names.py --census    print the conformance census, exit 0
"""
from __future__ import annotations

import re
import subprocess
import sys

# =================================================================================================
# LAYER 0.1 -- CONFORMANCE SCOPE.  A tree is exempt only for a reason that would still be true if
# somebody disagreed with this specification.  "We would rather not" is not on the list.
# =================================================================================================
