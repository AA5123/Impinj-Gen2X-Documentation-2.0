# THE REFERENCE BANNER IS FRONT MATTER NOW, NOT A BLOCKQUOTE — changed 2026-09-10 with the
# site-wide M1 rollout. It used to be emitted into the BODY as
#
#     > 📕 **REFERENCE** · **Audience:** {audience} · **Use:** {use}
#
# which meant every generated page opened with a <blockquote> — an element that means "this is
# quoted from somewhere else" wrapped around metadata about the page you are on — rendered at
# body size, led by an emoji whose colour the reader's operating system picks. The same line on
# the 141 authored pages was converted to `doc_type` + `page_meta` front matter and is drawn by
# src/components/PageMeta; leaving the generator emitting the old shape would have split the
# site's 236 routes into two incompatible treatments the moment anyone ran the generator.
#
# `doc_type: reference` is FIXED and not templated: this emitter builds the MQTT API reference
# and nothing else, which is the same reasoning `_singleton_frontmatter`'s `type: reference`
# already rests on.
PAGE_META = (
    "doc_type: reference\n"
    "page_meta:\n"
    '  - "Audience: {audience}"\n'
    '  - "Use: {use}"'
)


def page_meta_lines(audience, use):
    """The two front-matter keys, YAML-escaped. Values reach YAML inside double quotes, so a
    literal quote or backslash in an authoring file's `use:` would otherwise end the scalar
    early and take the build down five steps from its cause — the same trap render_frontmatter's
    own `q()` was written for, which is why this does not just call .format()."""
    def q(v):
        return str(v).replace("\\", "\\\\").replace('"', '\\"')
    return PAGE_META.format(audience=q(audience), use=q(use))
