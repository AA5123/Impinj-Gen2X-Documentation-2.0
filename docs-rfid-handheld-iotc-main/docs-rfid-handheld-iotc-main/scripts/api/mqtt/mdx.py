"""
mdx.py — Canonical-Grid MDX emitter.

Assembles a routed api/mqtt/reference/<plane>/<doc-id>.mdx from:
  * schema-derived AUTO/hybrid sections (rows/JSON consts, Request/Response/Event
    Payload, Response Codes, Topic Mapping skeleton, Examples bodies), and
  * human prose pulled from the per-op guided authoring file (Overview, When to
    Use, semantics, Lifecycle, Notes and Caveats, Details/Key-Fields human rows,
    per-field desc/enumUnits overrides, Related line, topic rows).

H2s ARE NOW CHECKED: strict-subsequence against config/spines.json, mandatory-slot
presence, no off-spine H2, and the heading/anchor pair together — cmd_check's sixth
gate, added 2026-09-08. Output still only AIMS AT, and is checked against by nothing:
a per-type callout budget with `danger` retired, Title-Case H2s, and the
plain-literal-ESM / no-`//` MDX constraints. Nothing below depth 2 is asserted, on
purpose (see classify.spine_findings).

This docstring used to say the output "obeys the section linter" and cite a
per-type ceiling in scripts/lint-admonitions.mjs. NEITHER FILE EXISTS -- not that
one and not scripts/lint-sections.mjs. The conventions above are real and the
emitter does follow them, but they are followed by habit and by this code, not by
enforcement, so a hand edit or a future change can break any of them silently.
See classify.py's module docstring and config/spines.json — the spine IS now
enforced, as cmd_check's sixth gate, but only at H2 and only over the generator's
own expected set. The callout budget and Title Case remain unenforced.
"""

