# ── H1's CARD SUMMARY ────────────────────────────────────────────────────────────────────────
# A DocCard clamps its description to TWO LINES, about 82 characters at the 304px text column the
# hub grid produces. `description` is a SEO field — it ships as <meta name="description"> and
# og:description, where 150-160 is the useful length — so a card fed the description always
# ellipsised. `sidebar_custom_props.card` carries the short form; src/theme/DocCard/Layout prefers
# it and falls back to the description.
#
# DERIVED HERE RATHER THAN AUTHORED, unlike the 214 hand-written pages, and the difference is that
# these 25 pages have no authoring file to put it in: their frontmatter is built from the routing
# manifest, so a hand-written card would be overwritten on the next `npm run gen:reference`. The
# rule is the same one that produced the authored set — first sentence, else the last strong
# boundary inside the budget — so a generated card and an authored one read alike.
CARD_LIMIT = 81
# The character count at which a second line begins in the 304px card description column. A
# shorter cut renders on one line against a box reserved for two.
CARD_MIN = 46

# The two whose first sentence has no boundary inside the budget. Keyed by doc_id, because that is
# what the manifest calls them and it is stable across a description rewrite.
CARD_OVERRIDES = {
    "set-post-filter": "Add, delete or replace the post-read filters on a data endpoint.",
    "get-eth": "Wired Ethernet state, link status and speed, and the DHCP IPv4 lease.",
    "get-status": "An on-demand snapshot of power, radio, clock, terminal and battery.",
    "get-operating-mode": "Read back the operating-mode configuration: profile, query, filters.",
    "get-post-filter": "Read back the post-read filters in force, per data endpoint.",
    "alerts-event": "The alert envelope, and the six alertDetails branches it carries.",
    "mqtt-connection-event": "The per-endpoint CONNECTED birth message and DISCONNECTED Last Will.",
    "config-endpoint": "Add, update, or delete an MQTT endpoint on the reader.",
    "response-codes": "Every response code: what it means, and which commands return it.",
    "delete-certificate": "Remove one certificate from the trust store, by name and by type.",
    "delete-wifi-profile": "Remove one saved Wi-Fi profile by ESSID; the active one is protected.",
    "get-endpoint-config": "Read back the active endpoint configuration and every saved name.",
    "get-installed-certificates": "List the trust store's certificates — metadata only, no private keys.",
    "install-certificate": "Add a certificate or key, by HTTP download or by inline content.",
    "set-os": "An over-the-air firmware update from a .DAT image URL. Asynchronous.",
    "control-operation": "START or STOP the radio, or the barcode scanner, on the CTRL endpoint.",
}

# "MQTT reference for get_status: a read-only, on-demand device-health snapshot…" — every
# operation page's description opens with this stem, and cutting at the first boundary would
# hand the card back the stem and nothing else ("MQTT reference for get_status."), which repeats
# the title the card already prints two lines above. The stem is dropped first so the budget is
# spent on what the operation DOES.
STEM_RE = re.compile(r"^MQTT reference for [^\s:]+\s*[:—-]\s*", re.I)


def card_summary(entry, description=None):
    """The card line: the LONGEST truthful prefix of the description that still fits two rendered
    lines, matching the rule the 214 authored pages use (see scripts' cardtext derivation).

    `description` overrides the entry's own when the caller has already resolved it — the
    singleton builder substitutes {code_range} from the contract, and a card built from the raw
    template would print the placeholder."""
    override = CARD_OVERRIDES.get(entry.get("doc_id"))
    if override:
        return override
    desc = (description if description is not None else entry.get("description") or "").strip()
    if not desc:
        return None
    desc = STEM_RE.sub("", desc)
    if desc:
        desc = desc[0].upper() + desc[1:]
    desc = re.sub(r"\s+", " ", desc)
    budget = CARD_LIMIT - 1          # the appended full stop
    cuts = [m.start() for m in re.finditer(r"(?<=[.!?])\s+|\s+—\s+|:\s+|;\s+|,\s+", desc)]
    cuts.append(len(desc))
    for i in sorted(set(cuts), reverse=True):
        c = desc[:i].rstrip(" ,;:—.")
        # Never cut inside a bracket — a comma inside a parenthetical would otherwise leave an
        # opening bracket with no close, and the card reads as an interrupted sentence.
        if c.count("(") != c.count(")"):
            continue
        if CARD_MIN <= len(c) <= budget:
            return c + "."
    for i in sorted(set(cuts), reverse=True):
        c = desc[:i].rstrip(" ,;:—.")
        if c.count("(") == c.count(")") and len(c) <= budget:
            return c + "."
    return None


def render_frontmatter(entry, kind, page_meta=None):
    def q(v):
        if v is None:
            return '""'
        return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'
    lines = ["---",
             f"id: {entry['doc_id']}",
             # Quoted like every other field here, and like the singleton builder
             # already does. Unquoted, a title containing a YAML indicator breaks
             # the page in three different ways: `Name: scope` throws, a leading
             # `#` parses to null, and `&warm reboot` silently becomes "reboot".
             # The colon form ("<EventName>: <one-line scope>") is exactly what a
             # reference page title takes, so this is not a rare shape — it is the
             # common one. (The rulebook that prescribed it was retired 2026-08-13;
             # the shape survives because the pages use it.) Nothing
             # between here and `npm run build` parses frontmatter, so the failure
             # would surface five lint steps away from its cause.
             f"title: {q(entry.get('title') or entry['doc_id'])}",
             f"sidebar_label: {q(entry.get('sidebar_label') or entry.get('title'))}",
             f"description: {q(entry.get('description') or '')}",
             ]
    if entry.get("emoji"):
        card = card_summary(entry)
        props = "emoji: " + q(entry["emoji"])
        if card:
            props += ", card: " + q(card)
        lines.append("sidebar_custom_props: { " + props + " }")
    lines.append(f"type: {kind}")
    # M1's two keys, when the caller has an audience/use to state. Appended LAST so the existing
    # five keys keep their order and a diff of a regenerated page reads as an addition rather
    # than a reshuffle.
    if page_meta:
        lines.append(page_meta)
    lines.append("---")
    return "\n".join(lines)


