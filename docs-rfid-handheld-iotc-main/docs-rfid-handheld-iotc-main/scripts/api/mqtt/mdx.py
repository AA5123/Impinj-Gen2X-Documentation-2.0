def render_code_catalog(rows, command_links=None):
    """Full response-code catalog. `rows` = list of dicts with keys
    code(int), kind, meaning, iot(str; '' -> em dash), cause, action,
    applies(list of command names, or containing '*' for all).

    Each row has a numeric anchor and each published command links to its page.
    The contract's commands[] scoping is the
    only provenance, so there is no second class of name left to mark -- see the
    retirement notes above for the two markers this catalog used to carry."""
    def text(value):
        return escape(str(value)).replace('{', '&#123;').replace('}', '&#125;')

    out = [
        '<div className="table-wrapper">',
        '<table>',
        '<thead><tr><th style={{textAlign: \'right\'}}>Code</th><th>Kind</th><th>Meaning</th><th>IoT status code</th>'
        '<th>Cause</th><th>Recommended action</th><th>Applies to</th></tr></thead>',
        '<tbody>',
    ]
    for r in rows:
        iot = r.get("iot") or ""
        iot_cell = f"<code>{text(iot)}</code>" if iot else "\u2014"
        applies = r.get("applies") or []
        if "*" in applies:
            applies_cell = "All commands"
        else:
            applies_cell = ", ".join(
                f'<Link to="{text(command_links[a])}"><code>{text(a)}</code></Link>'
                if command_links and a in command_links else f"<code>{text(a)}</code>"
                for a in applies) or "\u2014"
        out.append(
            f'<ResponseCodeRow id="code-{r["code"]}"><td style={{{{textAlign: \'right\'}}}}><code>{r["code"]}</code></td>'
            f'<td>{text(r["kind"])}</td><td>{text(r["meaning"])}</td><td>{iot_cell}</td>'
            f'<td>{text(r["cause"])}</td><td>{text(r["action"])}</td><td>{applies_cell}</td></ResponseCodeRow>'
        )
    out.extend(['</tbody>', '</table>', '</div>'])
    return "\n".join(out)


def render_codes_by_command(rows, command_links=None):
    """Command -> response codes matrix. `rows` = list of (command, [int codes]).

    Every code now comes from one source — the AsyncAPI contract's own
    `commands[]` scoping, unioned with the universal codes — so there is no
    provenance distinction left to mark and no overlay to merge."""
    head = "| Command | Response codes |\n| --- | --- |"
    out = [head]
    for cmd, codes in rows:
        chips = " · ".join(f"`{c}`" for c in codes)
        label = (f"[`{_cell(cmd)}`]({command_links[cmd]})"
                 if command_links and cmd in command_links else f"`{_cell(cmd)}`")
        out.append(f"| {label} | {chips} |")
    return "\n".join(out)
