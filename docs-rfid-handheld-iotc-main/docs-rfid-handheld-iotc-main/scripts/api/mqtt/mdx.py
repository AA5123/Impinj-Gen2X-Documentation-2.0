# --------------------------------------------------------------------------- #
# Closed vocabularies for the Topic Mapping table — one fact per column: MESSAGE
# (role) + DIRECTION (flow), never role+verb+actor fused into one cell.
#
# This used to say "Mirrors scripts/lint-sections.mjs rule 11; keep the two in
# sync". That file does not exist, so there is nothing to keep in sync and nothing
# checking the vocabulary. Note also that render_topic_table is currently UNREACHED:
# every routing-manifest entry carries "topics": [], so it returns "" for all 24
# pages and each Topic Mapping table is hand-typed in prose. The AsyncAPI contract
# does carry the addresses (26/26 operations resolve a channel address, 20/20
# receive ops declare a reply channel), so this table becomes generable once the
# contract feeds it.
TOPIC_MESSAGES = ("Request", "Response", "Event")
# Message role -> canonical flow. The app publishes the request; the reader
# publishes the reply and every event. This is a closed 2-value flow.
TOPIC_ROLE_DIRECTION = {
    "Request": "App → Reader",   # App → Reader
    "Response": "Reader → App",  # Reader → App
    "Event": "Reader → App",     # Reader → App
}


def render_topic_table(topics):
    """Render the Topic Mapping table from routing-manifest.topics rows.

    Each row is a dict {message, topic, note, [plane], [direction]}. `direction`
    is DERIVED from `message` via TOPIC_ROLE_DIRECTION (a closed 2-value flow) and
    is never free-typed unless a row overrides it explicitly. A leading `Plane`
    column is emitted iff ANY row carries a `plane` (multi-plane ops such as
    control_operation); single-plane ops stay 4-column. Placeholder tokens
    (`<tenantId>`, `<serial>`) are authored in each `topic` value, not synthesised.
    Returns '' when there are no rows (the op authors the table in prose instead;
    the assembler then emits the prose and never a second, generated table)."""
    if not topics:
        return ""
    has_plane = any(t.get("plane") for t in topics)
    cols = (["Plane"] if has_plane else []) + ["Message", "Direction", "Topic", "Note"]
    head = "| " + " | ".join(cols) + " |\n| " + " | ".join("---" for _ in cols) + " |"
    rows = []
    for t in topics:
        msg = t.get("message", "")
        if msg not in TOPIC_ROLE_DIRECTION:
            raise ValueError(
                f"render_topic_table: unknown message role {msg!r} "
                f"(expected one of {TOPIC_MESSAGES})")
        direction = t.get("direction") or TOPIC_ROLE_DIRECTION[msg]
        cells = ([t.get("plane", "")] if has_plane else []) + [
            msg, direction, t.get("topic", ""), t.get("note", "")]
        rows.append("| " + " | ".join(cells) + " |")
    return head + "\n" + "\n".join(rows)


def render_response_codes(codes):
    head = "| Code | Description |\n| --- | --- |"
    rows = []
    for c in codes:
        code = c.get("code")
        desc = (c.get("description") or "").strip().replace("\n", " ")
        rows.append(f"| `{code}` | {desc} |")
    return head + "\n" + "\n".join(rows)


# --------------------------------------------------------------------------- #
# Response-codes singleton tables. The catalogue is an HTML table so each row can carry
# an id; the matrix is GFM. Every link and anchor resolves under onBrokenLinks/onBrokenAnchors: throw.
# --------------------------------------------------------------------------- #
def _cell(v):
    """Escape a value for a GFM table cell: collapse newlines, escape pipes."""
    return str(v).replace("\r", " ").replace("\n", " ").replace("|", "\\|").strip()


