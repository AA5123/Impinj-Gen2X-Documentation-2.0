# --------------------------------------------------------------------------- #
# ESM value rendering — plain JS literals (no computed exprs, no `//` comments)
# --------------------------------------------------------------------------- #
def _js_str(s):
    """Single-quoted JS string with minimal escaping (matches authored style)."""
    s = str(s)
    if "'" in s and '"' not in s:
        return '"' + s.replace("\\", "\\\\").replace("\n", "\\n") + '"'
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


def _js_val(v, indent):
    pad = "  " * indent
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return json.dumps(v)
    if isinstance(v, str):
        return _js_str(v)
    if isinstance(v, list):
        if not v:
            return "[]"
        if all(not isinstance(x, (dict, list)) for x in v):
            return "[" + ", ".join(_js_val(x, indent) for x in v) + "]"
        inner = ",\n".join(pad + "  " + _js_val(x, indent + 1) for x in v)
        return "[\n" + inner + ",\n" + pad + "]"
    if isinstance(v, (dict, OrderedDict)):
        if not v:
            return "{}"
        # inline when no value is a dict or a list-of-dicts (matches authored
        # compact style: leaf rows on one line; rows with `children` multi-line)
        def _nested(x):
            return isinstance(x, (dict, OrderedDict)) or (
                isinstance(x, list) and any(isinstance(i, (dict, OrderedDict)) for i in x))
        if not any(_nested(val) for val in v.values()):
            inner = ", ".join(_js_key(k) + ": " + _js_val(val, indent) for k, val in v.items())
            return "{ " + inner + " }"
        parts = []
        for k, val in v.items():
            parts.append(pad + "  " + _js_key(k) + ": " + _js_val(val, indent + 1))
        return "{\n" + ",\n".join(parts) + ",\n" + pad + "}"
    return _js_str(v)


def _js_key(k):
    import re
    return k if re.match(r"^[A-Za-z_$][A-Za-z0-9_$]*$", str(k)) else _js_str(k)


def render_row_const(name, rows):
    """`export const NAME = [ ...rows... ];` — rows are SchemaRow dicts (dropping
    None enumUnits/example so cells match the authored style)."""
    cleaned = [_clean_row(r) for r in rows]
    return f"export const {name} = " + _js_val(cleaned, 0) + ";"


def _clean_row(r):
    out = OrderedDict()
    out["field"] = r["field"]
    out["type"] = r["type"]
    out["required"] = bool(r.get("required"))
    if r.get("enumUnits") is not None:
        out["enumUnits"] = r["enumUnits"]
    if r.get("example") is not None:
        out["example"] = r["example"]
    out["desc"] = r.get("desc") or ""
    if r.get("children"):
        out["children"] = [_clean_row(c) for c in r["children"]]
    return out


def render_json_const(name, obj):
    return f"export const {name} = " + _js_val(obj, 0) + ";"


